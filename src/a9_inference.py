"""A9 (s(CASP) inference engine): compiles the in-force program Π_τ for date τ into s(CASP) syntax.

Encoding decisions (the "why"):
  - `exception_of(E, U)` must *block* U's default rule → encoded with negation-as-failure:
        blocked(U) :- exception_of(_, U).
        holds(U)   :- in_force(U), not blocked(U).
  - A8 rules keep their premises as quoted atoms (`premise(Rid, Text).` facts). Turning legal
    text into logical atoms is S_know's job; A9 only preserves them verbatim so the .pl is always
    syntactically valid regardless of how well the LLM normalized the atoms.

Run: python -I src/a9_inference.py <file md> [--versions a4_<name>_versions.jsonl --date YYYY-MM-DD] [--query "holds('ID')"]
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import a2_edges as a2
import a4_versions as a4

ROOT = a2.ROOT
OUT_DIR = a2.PROCESSED_DIR
DOCS_DIR = ROOT / "docs"


def _tag(versions, date):
    if versions is None:
        return None
    stem = Path(versions).stem
    m = re.fullmatch(r"a4_(.+)_versions", stem)
    name = m.group(1) if m else stem
    return f"{name}_{date}"


def atom(x):
    """Safe Prolog constant: single-quoted, escapes embedded quotes/backslashes."""
    return "'" + str(x).replace("\\", "\\\\").replace("'", "\\'") + "'"


def active_codes(src, versions=None, date=None):
    if versions is None:
        return list(a2.read_units(src).keys())
    return [r["id"] for r in a4.active_rows(a4.read_jsonl(versions), date)]


def read_rows(path):
    path = Path(path)
    if not path.exists():
        return []
    rows = []
    with open(path, encoding="utf-8", newline="") as f:
        for line in f:
            if line.strip():
                rows.append(json.loads(line))
    return rows


def structural_edges(codes):
    active = set(codes)
    edges = []
    for code in codes:
        parent = a2.parent_of(code)
        if parent and parent in active:
            edges.append((parent, "contains", code))
            edges.append((code, "part_of", parent))
    return edges

def exception_rows(src, versions, date):
    stem = Path(src).stem
    tag = _tag(versions, date)
    rows = []
    rows += read_rows(OUT_DIR / f"a3_exceptions_{stem}.jsonl")
    rows += read_rows(OUT_DIR / f"a6_exceptions_{stem}.jsonl")
    rows += read_rows(OUT_DIR / f"a8_implicit_exceptions_{stem}{'_' + tag if tag else ''}.jsonl")
    return rows


def refers_rows(src):
    return read_rows(OUT_DIR / f"a2_refs_{Path(src).stem}.jsonl")


def a8_rules(src, versions, date):
    stem = Path(src).stem
    tag = _tag(versions, date)
    return read_rows(OUT_DIR / f"a8_rules_{stem}{'_' + tag if tag else ''}.jsonl")


def render_program(src, versions=None, date=None, query=None):
    codes = active_codes(src, versions, date)
    active = set(codes)
    tag = _tag(versions, date)
    L = ["% s(CASP) program generated by src/a9_inference.py",
         f"% base: {Path(src).stem}, date: {date or '(base state)'}",
         "% Compile: scasp <file>.pl", ""]

    for c in codes:
        L.append(f"in_force({atom(c)}).")
    L.append("")
    for s, p, o in structural_edges(codes):
        L.append(f"{p}({atom(s)}, {atom(o)}).")
    for r in refers_rows(src):
        if r.get("p") == "refers_to" and r["s"] in active and r["o"] in active:
            L.append(f"refers_to({atom(r['s'])}, {atom(r['o'])}).")
    L.append("")

    exc = []
    for r in exception_rows(src, versions, date):
        if r.get("p") == "exception_of" and r.get("o") in active:
            exc.append((r["s"], r["o"]))
            L.append(f"exception_of({atom(r['s'])}, {atom(r['o'])}).")
    L.append("")

    L.append("% block default rule of U iff some exception targets U (negation-as-failure)")
    L.append("blocked(U) :- exception_of(_, U).")
    L.append("holds(U) :- in_force(U), not blocked(U).")
    L.append("")

    rules = [r for r in a8_rules(src, versions, date) if r.get("source") in active]
    for r in rules:
        rid = r.get("id") or f"r_{len(L)}"
        body = "".join(f", premise({atom(rid)}, {atom(b)})" for b in r.get("body", []))
        L.append(f"% rule {rid} (source {r.get('source')}): {r.get('head', '')}")
        L.append(f"conclusion({atom(rid)}) :- in_force({atom(r['source'])}){body}, not blocked({atom(r['source'])}).")
        for b in r.get("body", []):
            L.append(f"premise({atom(rid)}, {atom(b)}).")
        L.append("")

    if query:
        L.append(f"?- {query}.")
    return "\n".join(L) + "\n", len(codes), len(exc), len(rules)

def run(src, versions=None, date=None, query=None):
    stem = Path(src).stem
    tag = _tag(versions, date)
    program, n_units, n_exc, n_rules = render_program(src, versions, date, query)
    out = OUT_DIR / f"a9_{stem}{'_' + tag if tag else ''}.pl"
    a4.write_text(program, out)
    lines = [f"A9 report (s(CASP)): {stem}" + (f" @ {date}" if tag else ""),
             f"in_force units: {n_units} | exception_of: {n_exc} | A8 rules in_force: {n_rules}",
             f"program: {out}",
             "blocking: blocked(U) :- exception_of(_, U). ; holds(U) :- in_force(U), not blocked(U)."]
    answer = None
    if query:
        scasp = shutil.which("scasp") or os.environ.get("SCASP") or ""
        if scasp:
            try:
                cp = subprocess.run([scasp, str(out)], capture_output=True, text=True, timeout=120)
                answer = cp.stdout or cp.stderr
            except (OSError, subprocess.TimeoutExpired) as e:
                answer = f"(scasp error: {e})"
        lines.append(f"query: {query}")
        if answer:
            lines.append("answer:\n" + answer)
        else:
            lines.append("(scasp not found — install scasp or set SCASP to execute)")
    text = "\n".join(lines) + "\n"
    print(text, end="")
    a4.write_text(text, DOCS_DIR / f"a9_report_{stem}{'_' + tag if tag else ''}.txt")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("path", help="source md, used to derive the stem")
    ap.add_argument("--versions", help="a4_<name>_versions.jsonl; time-aware inference at --date")
    ap.add_argument("--date", help="YYYY-MM-DD, required with --versions")
    ap.add_argument("--query", help="s(CASP) query, e.g. holds('BLDS2015.D615.K1')")
    args = ap.parse_args(argv)
    if (args.versions is None) != (args.date is None):
        ap.error("--versions and --date must be passed together")
    if args.date is not None:
        args.date = a4.parse_iso(args.date).isoformat()
    return run(args.path, args.versions, args.date, args.query)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    raise SystemExit(main())